# история и обществознание — только для гуманитарных областей,
# иначе «история Вселенной» превратится в урок истории
HUM_FIELDS = {"hum", "lit", "art", "media", "ling", "edu", "career"}
HIST = _rx(r"истори", r"императ", r"\bцарств", r"\bправлени", r"\bвек[ауе]?\b", r"\bвеков\b", r"революц", r"\bвойн", r"археолог", r"\bимпери", r"\bцар[ьяи]\b",
           r"династи", r"средневеков", r"античн", r"древн", r"\bкнязь", r"\bдекабрист", r"\bСССР\b", r"\bсоветск",
           r"летопис", r"\bРомановы", r"Рюрикович", r"Отечествен\w* войн", r"краевед")
LAW = _rx(r"\bправ[ао]\b", r"\bправов", r"юрид", r"юрист", r"\bзакон", r"судебн", r"\bсуды\b",
          r"конституци")
SOC = _rx(r"обществ", r"социолог", r"\bсоциальн", r"\bполитолог", r"\bгосударств", r"\bгражданск\w* общ",
          r"антрополог", r"этнограф", r"\bфилософ", r"психолог")

INF_TITLE = _rx(r"алгоритм", r"нейросет", r"искусственн\w* интеллект", r"\bИИ\b", r"\bAI\b", r"artificial intelligence",
                r"\bроботот", r"программ\w* код", r"\bкомпьютер")
ART = _rx(r"живопис", r"\bмузык", r"архитектур", r"скульптур", r"\bбалет", r"\bопер[аыу]\b", r"\bтеатр", r"\bхудожник",
          r"\bикон[аыу]?\b", r"иконограф", r"\bгравюр", r"\bдизайн")
HIST_STRONG = _rx(r"\bистори(я|и|ю|ей|ческ)", r"археолог", r"революц", r"декабрист", r"Отечествен\w* войн",
                  r"Перв\w* миров\w* войн", r"Втор\w* миров\w* войн", r"Гражданск\w* войн", r"\bкраевед", r"\bлетопис")

def subjects_for(e):
    fields = [e.get("field")] + [f for f in (e.get("fields") or []) if f != e.get("field")]
    fields = [f for f in fields if f]
    text = " ".join(str(e.get(k) or "") for k in ("title", "desc", "series"))
    out = []
    def add(s):
        if s not in out:
            out.append(s)
    for f in fields:
        for s in BY_FIELD.get(f, []):
            add(s)
    for s, rx in ANY:
        if rx.search(text):
            add(s)
    title = " ".join(str(e.get(k) or "") for k in ("title", "series"))
    if INF_TITLE.search(title):
        add("inf")
    if ART.search(text) and ({"art", "hum", "lit", "media"} & set(fields)):
        add("art")
    if HUM_FIELDS & set(fields):
        # для «Общества и истории» годится широкий список слов, для остальных — только явная история
        if ("hum" in fields and HIST.search(text)) or HIST_STRONG.search(text):
            add("hist")
        if SOC.search(text):
            add("soc")
        if LAW.search(text):
            add("law")
    if "hum" in fields and not ({"hist", "soc", "econ", "law"} & set(out)):
        add("soc")
    # «Физика и техника» без явной физики и без техники в тексте — это физика
    if "phys" in fields and not ({"phys", "tech", "math"} & set(out)):
        add("phys")
    return [s for s in SUBJECTS if s in out]
